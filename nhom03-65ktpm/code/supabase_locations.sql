CREATE TABLE IF NOT EXISTS public.document_locations (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id BIGINT NOT NULL UNIQUE REFERENCES public.documents(id) ON DELETE CASCADE,
  latitude    DOUBLE PRECISION,
  longitude   DOUBLE PRECISION,
  place_name  TEXT,
  shelf       TEXT,
  note        TEXT,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_document_locations_doc_id
  ON public.document_locations (document_id);

-- Trigger tự cập nhật updated_at
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS update_document_locations_updated_at ON public.document_locations;
CREATE TRIGGER update_document_locations_updated_at
  BEFORE UPDATE ON public.document_locations
  FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();

-- Bật RLS
ALTER TABLE public.document_locations ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Location: chủ tài liệu và người được chia sẻ đọc được" ON public.document_locations;
DROP POLICY IF EXISTS "Location: chủ tài liệu ghi được" ON public.document_locations;
DROP POLICY IF EXISTS "Location: chủ tài liệu xóa được" ON public.document_locations;

-- Đọc: chủ tài liệu hoặc người có quyền viewer/editor/owner
CREATE POLICY "Location: chủ tài liệu và người được chia sẻ đọc được"
  ON public.document_locations FOR SELECT
  USING (
    EXISTS (
      SELECT 1 FROM public.documents d
      WHERE d.id = document_id
        AND (
          d.user_id = current_user_id()
          OR EXISTS (
            SELECT 1 FROM public.permissions p
            WHERE p.document_id = document_id
              AND p.user_id = current_user_id()
          )
        )
    )
  );

-- Ghi (INSERT / UPDATE): chủ tài liệu hoặc editor
CREATE POLICY "Location: chủ tài liệu ghi được"
  ON public.document_locations FOR ALL
  USING (
    EXISTS (
      SELECT 1 FROM public.documents d
      WHERE d.id = document_id
        AND d.user_id = current_user_id()
    )
  )
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM public.documents d
      WHERE d.id = document_id
        AND d.user_id = current_user_id()
    )
  );

-- Realtime
DO $$
BEGIN
  ALTER PUBLICATION supabase_realtime ADD TABLE public.document_locations;
EXCEPTION
  WHEN duplicate_object THEN NULL;
END $$;
