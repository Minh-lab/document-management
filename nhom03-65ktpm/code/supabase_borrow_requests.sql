-- Chạy sau supabase_schema.sql, supabase_rls_policies.sql và
-- supabase_notifications.sql.
-- Các thao tác đổi trạng thái được thực hiện trong RPC để tránh cập nhật dở dang
-- giữa trạng thái yêu cầu, quyền truy cập và thông báo.

ALTER TABLE public.documents
  ADD COLUMN IF NOT EXISTS is_borrowable BOOLEAN NOT NULL DEFAULT FALSE;

CREATE INDEX IF NOT EXISTS idx_documents_borrowable
  ON public.documents (created_at DESC)
  WHERE is_borrowable = TRUE;

CREATE TABLE IF NOT EXISTS public.borrow_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id BIGINT NOT NULL REFERENCES public.documents(id) ON DELETE CASCADE,
  borrower_id TEXT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  owner_id TEXT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  note TEXT,
  rejection_reason TEXT,
  status TEXT NOT NULL DEFAULT 'pending'
    CHECK (status IN (
      'pending', 'approved', 'rejected', 'cancelled',
      'return_requested', 'returned', 'expired'
    )),
  due_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_borrow_requests_owner_status
  ON public.borrow_requests (owner_id, status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_borrow_requests_borrower_status
  ON public.borrow_requests (borrower_id, status, created_at DESC);

-- Chặn yêu cầu trùng đồng thời ở tầng cơ sở dữ liệu, kể cả khi hai client
-- gửi yêu cầu gần như cùng lúc.
CREATE UNIQUE INDEX IF NOT EXISTS idx_borrow_requests_one_active_per_user
  ON public.borrow_requests (document_id, borrower_id)
  WHERE status IN ('pending', 'approved', 'return_requested');
CREATE UNIQUE INDEX IF NOT EXISTS idx_borrow_requests_one_active_loan_per_document
  ON public.borrow_requests (document_id)
  WHERE status IN ('approved', 'return_requested');

ALTER TABLE public.borrow_requests ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Borrow requests are visible to participants"
  ON public.borrow_requests;
CREATE POLICY "Borrow requests are visible to participants"
  ON public.borrow_requests FOR SELECT
  USING (borrower_id = auth.uid()::TEXT OR owner_id = auth.uid()::TEXT);

DROP POLICY IF EXISTS "Borrowable documents are discoverable"
  ON public.documents;

CREATE OR REPLACE VIEW public.borrowable_documents AS
SELECT id, title, description, category_id, user_id, is_borrowable,
       created_at, updated_at
FROM public.documents
WHERE is_borrowable = TRUE
  AND auth.uid() IS NOT NULL
  AND user_id <> auth.uid()::TEXT;
GRANT SELECT ON public.borrowable_documents TO anon, authenticated;

DROP POLICY IF EXISTS "Approved borrowers can view borrowed documents"
  ON public.documents;
CREATE POLICY "Approved borrowers can view borrowed documents"
  ON public.documents FOR SELECT
  USING (
    EXISTS (
      SELECT 1
      FROM public.borrow_requests br
      WHERE br.document_id = documents.id
        AND br.borrower_id = auth.uid()::TEXT
        AND br.status IN ('approved', 'return_requested')
        AND br.due_at > NOW()
    )
  );

CREATE OR REPLACE FUNCTION public.validate_borrow_request_transition()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    IF NEW.status <> 'pending' THEN
      RAISE EXCEPTION 'Yêu cầu mượn mới phải ở trạng thái chờ duyệt';
    END IF;
    RETURN NEW;
  END IF;

  IF NEW.status = OLD.status THEN
    RETURN NEW;
  END IF;

  IF OLD.status = 'pending' AND NEW.status IN ('approved', 'rejected') THEN
    IF auth.uid()::TEXT IS DISTINCT FROM OLD.owner_id THEN
      RAISE EXCEPTION 'Chỉ chủ tài liệu mới được duyệt yêu cầu';
    END IF;
  ELSIF OLD.status = 'pending' AND NEW.status = 'cancelled' THEN
    IF auth.uid()::TEXT IS DISTINCT FROM OLD.borrower_id THEN
      RAISE EXCEPTION 'Chỉ người mượn mới được hủy yêu cầu';
    END IF;
  ELSIF OLD.status = 'approved' AND NEW.status = 'return_requested' THEN
    IF auth.uid()::TEXT IS DISTINCT FROM OLD.borrower_id THEN
      RAISE EXCEPTION 'Chỉ người mượn mới được báo đã trả';
    END IF;
  ELSIF OLD.status = 'return_requested' AND NEW.status = 'returned' THEN
    IF auth.uid()::TEXT IS DISTINCT FROM OLD.owner_id THEN
      RAISE EXCEPTION 'Chỉ chủ tài liệu mới được xác nhận đã nhận lại';
    END IF;
  ELSIF OLD.status IN ('approved', 'return_requested')
      AND NEW.status = 'expired' THEN
    IF OLD.due_at > NOW() THEN
      RAISE EXCEPTION 'Chỉ yêu cầu đã đến hạn mới được đánh dấu quá hạn';
    END IF;
  ELSE
    RAISE EXCEPTION 'Không thể chuyển trạng thái yêu cầu mượn từ % sang %',
      OLD.status, NEW.status;
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS borrow_request_transition_guard
  ON public.borrow_requests;
CREATE TRIGGER borrow_request_transition_guard
  BEFORE INSERT OR UPDATE OF status ON public.borrow_requests
  FOR EACH ROW EXECUTE FUNCTION public.validate_borrow_request_transition();

CREATE OR REPLACE FUNCTION public.notify_borrow_request_event()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  document_title TEXT;
  borrower_name TEXT;
BEGIN
  SELECT title INTO document_title
  FROM public.documents
  WHERE id = NEW.document_id;

  SELECT COALESCE(display_name, email, 'Người dùng')
  INTO borrower_name
  FROM public.users
  WHERE id = NEW.borrower_id;

  IF TG_OP = 'INSERT' THEN
    INSERT INTO public.notifications (user_id, title, body, type, document_id)
    VALUES (
      NEW.owner_id,
      'Yêu cầu mượn tài liệu mới',
      borrower_name || ' muốn mượn "' || COALESCE(document_title, 'tài liệu') || '".',
      'borrow_request',
      NEW.document_id
    );
    RETURN NEW;
  END IF;

  IF NEW.status IS DISTINCT FROM OLD.status THEN
    IF NEW.status IN ('approved', 'rejected', 'expired') THEN
      INSERT INTO public.notifications (user_id, title, body, type, document_id)
      VALUES (
        NEW.borrower_id,
        CASE NEW.status
          WHEN 'approved' THEN 'Yêu cầu mượn đã được duyệt'
          WHEN 'rejected' THEN 'Yêu cầu mượn đã bị từ chối'
          ELSE 'Yêu cầu mượn đã quá hạn'
        END,
        CASE NEW.status
          WHEN 'approved' THEN 'Bạn có thể truy cập tài liệu đến '
            || to_char(NEW.due_at, 'DD/MM/YYYY HH24:MI') || '.'
          WHEN 'rejected' THEN COALESCE(NEW.rejection_reason, 'Chủ tài liệu đã từ chối yêu cầu.')
          ELSE 'Quyền truy cập tài liệu đã hết hạn.'
        END,
        'borrow_decision',
        NEW.document_id
      );
    ELSIF NEW.status = 'return_requested' THEN
      INSERT INTO public.notifications (user_id, title, body, type, document_id)
      VALUES (
        NEW.owner_id,
        'Người mượn đã trả tài liệu',
        borrower_name || ' báo đã trả "' || COALESCE(document_title, 'tài liệu')
          || '". Hãy xác nhận đã nhận lại.',
        'borrow_return',
        NEW.document_id
      );
    ELSIF NEW.status = 'returned' THEN
      INSERT INTO public.notifications (user_id, title, body, type, document_id)
      VALUES (
        NEW.borrower_id,
        'Đã xác nhận trả tài liệu',
        'Chủ tài liệu xác nhận đã nhận lại "' || COALESCE(document_title, 'tài liệu') || '".',
        'borrow_return',
        NEW.document_id
      );
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS borrow_request_notifications
  ON public.borrow_requests;
CREATE TRIGGER borrow_request_notifications
  AFTER INSERT OR UPDATE OF status ON public.borrow_requests
  FOR EACH ROW EXECUTE FUNCTION public.notify_borrow_request_event();

CREATE OR REPLACE FUNCTION public.create_borrow_request(
  p_document_id BIGINT,
  p_note TEXT,
  p_due_at TIMESTAMPTZ
)
RETURNS BIGINT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  current_uid TEXT := auth.uid()::TEXT;
  document_owner TEXT;
  request_id BIGINT;
BEGIN
  IF current_uid IS NULL THEN
    RAISE EXCEPTION 'Bạn cần đăng nhập để gửi yêu cầu mượn';
  END IF;
  IF p_due_at <= NOW() OR p_due_at > NOW() + INTERVAL '365 days' THEN
    RAISE EXCEPTION 'Thời hạn mượn phải nằm trong 365 ngày tới';
  END IF;

  SELECT user_id INTO document_owner
  FROM public.documents
  WHERE id = p_document_id AND is_borrowable = TRUE;
  IF document_owner IS NULL THEN
    RAISE EXCEPTION 'Tài liệu không tồn tại hoặc hiện không cho phép mượn';
  END IF;
  IF document_owner = current_uid THEN
    RAISE EXCEPTION 'Bạn không thể mượn tài liệu của chính mình';
  END IF;

  INSERT INTO public.borrow_requests (
    document_id, borrower_id, owner_id, note, due_at
  )
  VALUES (
    p_document_id, current_uid, document_owner, NULLIF(BTRIM(p_note), ''), p_due_at
  )
  RETURNING id INTO request_id;

  RETURN request_id;
EXCEPTION
  WHEN unique_violation THEN
    RAISE EXCEPTION 'Bạn đã có yêu cầu mượn đang chờ hoặc một lượt mượn chưa hoàn tất';
END;
$$;

CREATE OR REPLACE FUNCTION public.respond_to_borrow_request(
  p_request_id BIGINT,
  p_approve BOOLEAN,
  p_reason TEXT DEFAULT NULL
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  request_row public.borrow_requests%ROWTYPE;
BEGIN
  SELECT * INTO request_row
  FROM public.borrow_requests
  WHERE id = p_request_id
  FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Không tìm thấy yêu cầu mượn';
  END IF;
  IF request_row.owner_id <> auth.uid()::TEXT THEN
    RAISE EXCEPTION 'Bạn không có quyền xử lý yêu cầu này';
  END IF;
  IF request_row.status <> 'pending' THEN
    RAISE EXCEPTION 'Yêu cầu này đã được xử lý';
  END IF;
  IF p_approve AND request_row.due_at <= NOW() THEN
    RAISE EXCEPTION 'Thời hạn mượn của yêu cầu này đã qua';
  END IF;
  IF p_approve AND NOT EXISTS (
    SELECT 1
    FROM public.documents d
    WHERE d.id = request_row.document_id
      AND d.is_borrowable = TRUE
  ) THEN
    RAISE EXCEPTION 'Chủ tài liệu đã tắt quyền cho mượn';
  END IF;
  IF p_approve AND EXISTS (
    SELECT 1
    FROM public.borrow_requests active_request
    WHERE active_request.document_id = request_row.document_id
      AND active_request.id <> request_row.id
      AND active_request.status IN ('approved', 'return_requested')
  ) THEN
    RAISE EXCEPTION 'Tài liệu đang được người khác mượn';
  END IF;

  UPDATE public.borrow_requests
  SET status = CASE WHEN p_approve THEN 'approved' ELSE 'rejected' END,
      rejection_reason = CASE WHEN p_approve THEN NULL ELSE NULLIF(BTRIM(p_reason), '') END,
      updated_at = NOW()
  WHERE id = p_request_id;
EXCEPTION
  WHEN unique_violation THEN
    RAISE EXCEPTION 'Tài liệu vừa được duyệt cho người mượn khác';
END;
$$;

CREATE OR REPLACE FUNCTION public.cancel_borrow_request(p_request_id BIGINT)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  UPDATE public.borrow_requests
  SET status = 'cancelled', updated_at = NOW()
  WHERE id = p_request_id
    AND borrower_id = auth.uid()::TEXT
    AND status = 'pending';
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Không thể hủy yêu cầu này';
  END IF;
END;
$$;

CREATE OR REPLACE FUNCTION public.request_borrow_return(p_request_id BIGINT)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  UPDATE public.borrow_requests
  SET status = 'return_requested', updated_at = NOW()
  WHERE id = p_request_id
    AND borrower_id = auth.uid()::TEXT
    AND status = 'approved'
    AND due_at > NOW();
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Không thể báo trả yêu cầu này';
  END IF;
END;
$$;

CREATE OR REPLACE FUNCTION public.confirm_borrow_return(p_request_id BIGINT)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  UPDATE public.borrow_requests
  SET status = 'returned', updated_at = NOW()
  WHERE id = p_request_id
    AND owner_id = auth.uid()::TEXT
    AND status = 'return_requested';
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Không thể xác nhận trả yêu cầu này';
  END IF;
END;
$$;

CREATE OR REPLACE FUNCTION public.expire_borrow_requests()
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  UPDATE public.borrow_requests
  SET status = 'expired', updated_at = NOW()
  WHERE status IN ('approved', 'return_requested')
    AND due_at <= NOW();
END;
$$;

