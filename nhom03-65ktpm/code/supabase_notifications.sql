create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id text not null,
  title text not null,
  body text,
  type text not null default 'system',
  document_id bigint references public.documents(id) on delete set null,
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists notifications_user_created_idx
  on public.notifications (user_id, created_at desc);

create index if not exists notifications_user_unread_idx
  on public.notifications (user_id, is_read);

alter table public.notifications enable row level security;

drop policy if exists "Notifications are readable" on public.notifications;
drop policy if exists "Notifications are insertable" on public.notifications;
drop policy if exists "Notifications are updatable" on public.notifications;

-- TODO: siết policy theo current_user_id() sau khi client gửi được x-user-id
-- hoặc Edge Function đồng bộ Supabase JWT hoạt động ổn định.
create policy "Notifications are readable"
  on public.notifications for select using (true);

create policy "Notifications are insertable"
  on public.notifications for insert with check (true);

create policy "Notifications are updatable"
  on public.notifications for update using (true);

-- Cho phép Realtime phát thay đổi của bảng.
do $$
begin
  alter publication supabase_realtime add table public.notifications;
exception
  when duplicate_object then null;
end $$;
