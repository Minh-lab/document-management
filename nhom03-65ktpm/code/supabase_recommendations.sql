-- 0. Bảng tag của UC-06 (Đạt) – giống hệt supabase_tags_schema.sql.
--    Dùng IF NOT EXISTS: nếu đã chạy file của Đạt thì giữ nguyên.
create table if not exists public.tags (
  id bigserial primary key,
  name text not null unique,
  color text
);

create table if not exists public.document_tags (
  document_id bigint not null references public.documents(id) on delete cascade,
  tag_id bigint not null references public.tags(id) on delete cascade,
  primary key (document_id, tag_id)
);

create index if not exists idx_document_tags_tag_id on public.document_tags (tag_id);

-- 1. Sở thích: trọng số của từng tag với từng người dùng
create table if not exists public.user_interests (
  user_id text not null,
  tag_id bigint not null references public.tags(id) on delete cascade,
  weight double precision not null default 0 check (weight >= 0),
  updated_at timestamptz not null default now(),
  primary key (user_id, tag_id)
);

-- 2. Lịch sử xem tài liệu (nguồn cho "lượt xem" và loại tài liệu vừa xem)
create table if not exists public.document_views (
  id bigint generated by default as identity primary key,
  document_id bigint not null references public.documents(id) on delete cascade,
  user_id text not null,
  viewed_at timestamptz not null default now()
);

create index if not exists document_views_document_idx on public.document_views (document_id);
create index if not exists document_views_user_idx on public.document_views (user_id, viewed_at desc);

-- 3. Bật RLS và KHÔNG mở policy: ứng dụng chỉ đọc/ghi qua các hàm bên dưới.
alter table public.user_interests enable row level security;
alter table public.document_views enable row level security;

-- 4. Ứng viên gợi ý: tài liệu của NGƯỜI KHÁC, chưa xem trong 7 ngày, kèm tag và lượt xem.
--    Chỉ trả thông tin mô tả (không có link / đường dẫn file).
create or replace function public.recommendation_candidates(p_user_id text)
returns table (
  id bigint, title text, description text, category_name text, owner_name text,
  created_at timestamptz, tags text[], view_count bigint, can_open boolean
)
language sql stable security definer set search_path = public as $$
  select d.id, d.title, d.description, c.name,
         coalesce(nullif(u.display_name, ''), u.email, ''),
         d.created_at,
         coalesce((select array_agg(t.name order by t.name)
                   from document_tags dt join tags t on t.id = dt.tag_id
                   where dt.document_id = d.id), '{}'),
         (select count(*) from document_views v where v.document_id = d.id),
         exists (select 1 from permissions p where p.document_id = d.id and p.user_id = p_user_id)
  from documents d
  join categories c on c.id = d.category_id
  left join users u on u.id = d.user_id
  where d.user_id <> p_user_id
    and not exists (select 1 from document_views v
                    where v.document_id = d.id and v.user_id = p_user_id
                      and v.viewed_at > now() - interval '7 days')
  order by d.created_at desc
  limit 200
$$;

-- 5. Sở thích của một người: tên tag -> trọng số
create or replace function public.user_interest_weights(p_user_id text)
returns table (tag_name text, weight double precision)
language sql stable security definer set search_path = public as $$
  select t.name, ui.weight
  from user_interests ui join tags t on t.id = ui.tag_id
  where ui.user_id = p_user_id and ui.weight > 0
$$;

-- 6. Mở tài liệu: ghi lượt xem + tăng sở thích các tag của tài liệu đó (+1)
create or replace function public.record_document_view(p_user_id text, p_document_id bigint)
returns void
language sql volatile security definer set search_path = public as $$
  insert into document_views (document_id, user_id) values (p_document_id, p_user_id);
  insert into user_interests (user_id, tag_id, weight)
    select p_user_id, dt.tag_id, 1 from document_tags dt where dt.document_id = p_document_id
  on conflict (user_id, tag_id)
    do update set weight = user_interests.weight + excluded.weight, updated_at = now();
$$;

-- 7. Gán tag (UC-06 gọi sau khi lưu tag): tăng sở thích các tag đó (+2)
create or replace function public.bump_tag_interests(
  p_user_id text, p_tag_ids bigint[], p_amount double precision default 2
)
returns void
language sql volatile security definer set search_path = public as $$
  insert into user_interests (user_id, tag_id, weight)
    select p_user_id, unnest(p_tag_ids), p_amount
  on conflict (user_id, tag_id)
    do update set weight = user_interests.weight + excluded.weight, updated_at = now();
$$;

grant execute on function
  public.recommendation_candidates(text),
  public.user_interest_weights(text),
  public.record_document_view(text, bigint),
  public.bump_tag_interests(text, bigint[], double precision)
to anon, authenticated;
